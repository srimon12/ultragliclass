#!/usr/bin/env python
"""Generates the typed-decisions ablation recipes + arm configs from the pilot recipe (configs/data_stage2_pilot.yaml).
Run from the project root:  python scripts/make_ablation_recipes.py     (deterministic; outputs are committed under configs/)

Arms (all = pilot arm C: many_label + consistency, same seed 42/43, same 1,500 x 64 rows, same init = S1, same val file):
  E1  no DEDICATED procedural rows procedural-typed-decisions 11,750 -> 0 ; freed rows filled with gliclass-v2.0 (47,100 -> 58,850).
                                   NB the Jev source itself carries 4,728 procedural-style rows (source tag procedural-typed-decisions/*, 20.1 % of
                                   its 23,500), so procedural-style share goes 17.2 % (pilot) -> 4.9 % (about S1's own share: ~20k of 410k rows)
  E1z E1 + ALSO no procedural-style Jev rows   (Jev n_train stays 23,500: drawn from the non-procedural rest) -> 0 % procedural (dose-response, optional)
  E2  E1 + semantic prose typed    + 3,000 rows of LocalLLaMA/typed-decisions TRAIN (customer_service + agent_trace_observability only,
                                   2 of the 4 eval workflows; invoice_processing and security_incidents stay unseen); gliclass 47,100 -> 55,850
  E3  C + semantic prose typed     procedural kept (11,750) ; + the same 3,000 semantic rows ; gliclass 47,100 -> 44,100
  C0  = the pilot C mix (reference rerun; OPTIONAL, same code and config as pilot C, only output names change)
Totals stay 96,035 train rows in every arm. All E arms (and the pilot arms) are evaluated on the SAME val file, calib/stage2_pilot_val.jsonl
(= the pilot's actual 1,850-row val set from the Kaggle output), so eval_loss is comparable; each arm's own prepare_data val.jsonl is not used."""
import copy, yaml

SRC = "configs/data_stage2_pilot.yaml"
base = yaml.safe_load(open(SRC))
SEM = [{"id": "LocalLLaMA/typed-decisions", "config": wf, "format": "system_one", "split": "train", "n_train": 1500, "n_val": 0,
        "answers_col": "gold", "max_state_chars": 4000, "license": "apache-2.0",
        "license_note": "dataset card: apache-2.0, synthetic; TRAIN split only (separate seed from test, per card). Same 4 workflows and the same "
                        "57 option strings as the eval (test) split -> in-schema data; test split is never read (prepare_data.py guard)."}
       for wf in ("customer_service", "agent_trace_observability")]
IDX = {s["id"]: i for i, s in enumerate(base["sources"])}


def gl(r): return next(s for s in r["sources"] if s["id"] == "knowledgator/gliclass-v2.0")
def proc(r): return next(s for s in r["sources"] if s["id"] == "tasksource/procedural-typed-decisions")


def jev(r): return next(s for s in r["sources"] if s["id"] == "tasksource/tasksource-jev-typed-decisions")


def make(arm, no_proc, sem, no_jev_proc=False):
    r = copy.deepcopy(base)
    r["name"] = f"stage2_abl_{arm}"; r["out_dir"] = f"data/stage2_abl_{arm}"
    drop = 11_750 if no_proc else 0
    if no_proc:
        proc(r)["n_train"] = 0
    if no_jev_proc:
        jev(r)["exclude_source_contains"] = "procedural-typed-decisions/"
    if sem:
        r["sources"] = r["sources"][:IDX["tasksource/procedural-typed-decisions"] + 1] + copy.deepcopy(SEM) + \
            r["sources"][IDX["tasksource/procedural-typed-decisions"] + 1:]
    gl(r)["n_train"] = gl(r)["n_train"] + drop - (3000 if sem else 0)
    hdr = (f"# Stage-2 ABLATION {arm} (generated by scripts/make_ablation_recipes.py from {SRC}; do not edit by hand).\n"
           f"# no_procedural={no_proc}  semantic_prose_typed={sem}.  Totals stay 96,035 train / 1,850 val; see STAGE2_ABLATION_JOB_SPEC.md.\n")
    open(f"configs/data_stage2_abl_{arm}.yaml", "w").write(hdr + yaml.safe_dump(r, sort_keys=False, width=140))


make("E1", True, False)
make("E1z", True, False, True)
make("E2", True, True)
make("E3", False, True)

for arm, desc in (("E1", "C minus the dedicated procedural dataset (filled with gliclass-v2.0)"),
                  ("E1z", "E1 and also minus the procedural-style rows inside Jev (0 % procedural)"),
                  ("E2", "E1 + 3,000 semantic prose-option typed rows (LocalLLaMA/typed-decisions TRAIN, 2 workflows)"),
                  ("E3", "C + the same 3,000 semantic rows in place of 3,000 gliclass rows (procedural kept)"),
                  ("C0", "pilot C unchanged (OPTIONAL noise/reproducibility rerun; same data recipe as pilot)")):
    data_dir = "data/stage2_pilot" if arm == "C0" else f"data/stage2_abl_{arm}"
    val = "data/stage2_pilot/val.jsonl" if arm == "C0" else "calib/stage2_pilot_val.jsonl"   # the pilot's ACTUAL val set (from the Kaggle output), shared by all arms
    open(f"configs/stage2_abl_{arm}.yaml", "w").write(
        f"# Stage-2 ABLATION arm {arm} = pilot arm C config ({desc}).\n"
        f"# Everything but the data files and output_dir is inherited from stage2_pilot_C.yaml (many_label on, consistency on, seed 42, 1,500 steps,\n"
        f"# S1 init). Data recipe: configs/data_stage2_abl_{arm}.yaml.\n"
        f"base: stage2_pilot_C.yaml\n"
        f"data:\n  train_files: [{data_dir}/train.jsonl]\n  val_files: [{val}]\n  many_label:\n    pools_file: {data_dir}/label_pools.json\n"
        f"train:\n  output_dir: runs/stage2_abl_{arm}\n")
print("ok")

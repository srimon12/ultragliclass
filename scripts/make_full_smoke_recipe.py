#!/usr/bin/env python
"""Tiny CPU-smoke version of configs/data_stage2_full.yaml (same sources / exclusions / forbid_ids; n_train scaled down, streaming with max_scan).
The two LocalLLaMA/typed-decisions TRAIN sources keep their full 1,500 rows each so the notebook's "exactly 3,000 typed-train rows" assert is exercised.
    python scripts/make_full_smoke_recipe.py -> configs/data_stage2_full_smoke.yaml (out_dir data/stage2_full, the path the notebook expects)"""
import yaml
r = yaml.safe_load(open("configs/data_stage2_full.yaml"))
r["name"] = "stage2_full_smoke"
r["out_dir"] = "data/stage2_full"
for s in r["sources"]:
    if s.get("enabled", True) is False:
        continue
    if s["id"] == "LocalLLaMA/typed-decisions":
        continue
    n = s["n_train"]
    s["n_train"] = 40 if n == "all" else (0 if int(n) == 0 else max(8, int(n) // 4000))
    s["n_val"] = max(6, s["n_val"] // 10) if s["n_val"] else 0
    s["max_scan"] = 6000
open("configs/data_stage2_full_smoke.yaml", "w").write("# generated by scripts/make_full_smoke_recipe.py (CPU smoke only, do not use on Kaggle)\n" + yaml.safe_dump(r, sort_keys=False, width=140))
print("wrote configs/data_stage2_full_smoke.yaml")

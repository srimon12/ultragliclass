#!/usr/bin/env python
"""Generates configs/data_stage2_full.yaml = the FULL stage-2 mix for the arm-C full run (Srimon, 24 Oct 2026).
Built from the ablation-E2 recipe (same sources, same licence notes, same forbid_ids, same seed 43 and the SAME n_val per source, so the
recipe's own val split equals the pilot val set calib/stage2_pilot_val.jsonl and carve-from-train sources never put a val row into train),
scaled to the source sizes of configs/data_stage2.yaml:
  - DBpedia, Bitext: DISABLED (D2, not approved).  banking77 / clinc: disabled (eval sets, D1).
  - tasksource/procedural-typed-decisions: n_train 0 (as E1/E2; val rows kept for comparability). Jev keeps its own procedural-style rows,
    capped so the procedural-style share stays at the E1 level (~4.9 %): Jev commercial (state <= 4,000 chars) = 581,758 rows of which
    113,083 (19.4 %) are procedural-style (counted on the box from the HF cache, 24 Oct) -> Jev n_train 437,000 => ~84.8k / ~1.74M = ~4.9 %.
  - LocalLLaMA/typed-decisions TRAIN split, customer_service + agent_trace_observability only, 1,500 + 1,500 rows (= ALL of those two
    workflows' train decisions; exactly as E2). Approved by Srimon (D10) for E2 and for this run; results are PARTLY IN-DOMAIN.
  - HWU64 kept (all x3): massive (shares 56/59 intent labels) is NOT zero-shot for this model; financial_phrasebank is NOT zero-shot either
    (twitter-financial-news-sentiment teaches the same 3-label task). Both must be reported as such.
  - gliclass-v2.0 n_train 1,090,000 (not 'all') so that the total is ~1.74M rows = just over ONE epoch of 27,000 steps x 64 rows
    (1,728,000): every row is seen at most once, the run stops at max_steps.
Run from the project root: python scripts/make_stage2_full_recipe.py"""
import copy, yaml

base = yaml.safe_load(open("configs/data_stage2_abl_E2.yaml"))
full = yaml.safe_load(open("configs/data_stage2.yaml"))
r = copy.deepcopy(base)
r["name"] = "stage2_full"
r["out_dir"] = "data/stage2_full"
N_TRAIN = {  # id[:config] -> (n_train, repeat)
    "knowledgator/gliclass-v2.0": (1_090_000, 1),
    "knowledgator/gliclass-v3-logic-dataset": ("all", 3),
    "tasksource/tasksource-jev-typed-decisions": (437_000, 1),
    "tasksource/procedural-typed-decisions": (0, 1),
    "LocalLLaMA/typed-decisions:customer_service": (1_500, 1),
    "LocalLLaMA/typed-decisions:agent_trace_observability": (1_500, 1),
    "DeepPavlov/hwu64": ("all", 3),
    "coastalcph/lex_glue:ledgar": (60_000, 1),
    "zeroshot/twitter-financial-news-topic": ("all", 2),
    "google-research-datasets/go_emotions:simplified": (40_000, 1),
    "zeroshot/twitter-financial-news-sentiment": ("all", 3),
}
seen = set()
for s in r["sources"]:
    key = s["id"] + (f":{s['config']}" if s.get("config") not in (None, "default", "all") else "")
    if s.get("enabled", True) is False:
        continue
    assert key in N_TRAIN, key
    n, rep = N_TRAIN[key]
    s["n_train"] = n
    if rep != 1 or "repeat" in s:
        s["repeat"] = rep
    seen.add(key)
assert seen == set(N_TRAIN), set(N_TRAIN) - seen
gl = next(s for s in r["sources"] if s["id"] == "knowledgator/gliclass-v2.0")
gl["pool_min_count"] = 5          # as configs/data_stage2.yaml (full gliclass vocabulary; pool capped at 20,000 labels)
for s in r["sources"]:            # disabled sources must stay disabled
    if any(x in s["id"] for x in ("DBPedia", "Bitext", "banking77", "clinc_oos")):
        assert s.get("enabled") is False, s["id"]
# v7: the carve-out only dedupes on (text, labels); the same TEXT under another label set reached train (835 rows on Kaggle, v2).
# Drop every train row whose text equals a val text (own val + the pilot val file); the val file itself is unchanged.
r["dedupe_train_vs_val"] = True
r["dedupe_val_files"] = ["calib/stage2_pilot_val.jsonl"]
hdr = ("# Stage-2 FULL run data recipe (arm C). GENERATED by scripts/make_stage2_full_recipe.py from configs/data_stage2_abl_E2.yaml +\n"
       "# the source sizes of configs/data_stage2.yaml. Do not edit by hand. See STAGE2_FULL_JOB_SPEC.md section 3 for the mix table.\n"
       "# Same seed (43) and n_val per source as the pilot/ablation => val == calib/stage2_pilot_val.jsonl; carved val rows never enter train;\n"
       "# v7: dedupe_train_vs_val drops every train row whose text equals a val text (prepare_data.py), so the leak check reads 0.\n"
       "# PARTLY IN-DOMAIN: 3,000 LocalLLaMA/typed-decisions TRAIN rows (2 of 4 workflows). massive + financial_phrasebank are NOT zero-shot.\n")
open("configs/data_stage2_full.yaml", "w").write(hdr + yaml.safe_dump(r, sort_keys=False, width=140))
print("wrote configs/data_stage2_full.yaml")

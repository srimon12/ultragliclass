#!/usr/bin/env python
"""Tiny CPU-smoke version of configs/data_stage2_pilot.yaml: same sources, same proportions, same exclusions, every n_train/n_val
divided by --scale (default 60, ~1.6k rows), streaming with max_scan so it runs in about a minute.
    python scripts/make_pilot_smoke_recipe.py  ->  configs/data_stage2_pilot_smoke.yaml  (out_dir data/stage2_pilot_smoke)"""
import argparse, copy, os, sys
import yaml
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ap = argparse.ArgumentParser()
ap.add_argument("--scale", type=int, default=60)
ap.add_argument("--src", default="configs/data_stage2_pilot.yaml")
ap.add_argument("--out", default="configs/data_stage2_pilot_smoke.yaml")
a = ap.parse_args()
r = yaml.safe_load(open(a.src))
r["name"] = "stage2_pilot_smoke"
r["out_dir"] = "data/stage2_pilot_smoke"
for s in r["sources"]:
    if s.get("enabled", True) is False:
        continue
    s["n_train"] = max(8, s["n_train"] // a.scale)
    s["n_val"] = max(6, s["n_val"] // 10)
    s["max_scan"] = 6000
open(a.out, "w").write("# generated by scripts/make_pilot_smoke_recipe.py from " + a.src + " (CPU smoke, do not edit)\n" + yaml.safe_dump(r, sort_keys=False))
print("wrote", a.out, "train rows ~", sum(s["n_train"] * s.get("repeat", 1) for s in r["sources"] if s.get("enabled", True) is not False))
